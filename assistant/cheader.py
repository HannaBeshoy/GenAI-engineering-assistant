"""C header generated in code from the validated register map (not by the model), so every
#define is traceable to a checked JSON entry."""
from __future__ import annotations

import re
from datetime import date

from .schemas import RegisterMap, ScaleFactors


def _ident(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()
    return s if s and not s[0].isdigit() else f"X_{s}"


def make_header(rmap: RegisterMap, scales: ScaleFactors | None = None) -> str:
    dev = _ident(rmap.device)
    guard = f"{dev}_REGS_H"
    out = [f"/* {rmap.device} register map", f" * Generated by genai-engineering-assistant on {date.today().isoformat()}",
           " * from the datasheet, extracted by an LLM and checked by rule-based validation.",
           " * Review against the datasheet before production use. */",
           f"#ifndef {guard}", f"#define {guard}", "", "#include <stdint.h>", ""]
    for r in sorted(rmap.registers, key=lambda r: int(r.address, 16)):
        out.append(f"/* {r.name} ({r.access}, reset {r.reset}): {r.description} */")
        out.append(f"#define {dev}_{r.name}_REG        {r.address.upper().replace('0X', '0x')}")
        out.append(f"#define {dev}_{r.name}_RESET      {r.reset.upper().replace('0X', '0x')}")
        for f in r.fields:
            if ":" in f.bits:
                hi, lo = sorted((int(x) for x in f.bits.split(":")), reverse=True)
            else:
                hi = lo = int(f.bits)
            mask = ((1 << (hi - lo + 1)) - 1) << lo
            name = f"{dev}_{r.name}_{_ident(f.name)}"
            out.append(f"#define {name}_POS   {lo}u")
            out.append(f"#define {name}_MSK   0x{mask:02X}u   /* bits {f.bits}: {f.description} */")
        out.append("")
    if scales and scales.scales:
        out.append("/* Sensitivity per full-scale setting (LSB per unit) */")
        for s in scales.scales:
            rng = s.range.replace("°/s", "DPS").replace("±", "").replace(" ", "")
            name = f"{dev}_SENS_{_ident(s.quantity)}_{re.sub(r'[^A-Za-z0-9]+', '_', rng).upper()}"
            out.append(f"#define {name}   {s.sensitivity:g}f   /* {s.reg}.{s.field} = {s.code}: {s.range}, {s.unit} */")
        out.append("")
    out.append(f"#endif /* {guard} */")
    return "\n".join(out) + "\n"
